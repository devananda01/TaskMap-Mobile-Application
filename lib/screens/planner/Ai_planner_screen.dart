// Figures out the status of session `index` given the full session list:
// the first not-yet-completed session is "up next", the rest are "pending".

class AiPlannerScreen extends ConsumerStatefulWidget {
  static const String routeName = "/planner";

  const AiPlannerScreen({super.key});

  @override
  ConsumerState<AiPlannerScreen> createState() => _AiPlannerScreenState();
}

class _AiPlannerScreenState extends ConsumerState<AiPlannerScreen> {
  // ── Form state ─────────────────────────────────────────────────────────────
  // Study availability slots
  final List<StudySlot> studySlots = [
    const StudySlot(
      start: TimeOfDay(hour: 9, minute: 0),
      end: TimeOfDay(hour: 11, minute: 0),
    ),
    const StudySlot(
      start: TimeOfDay(hour: 19, minute: 0),
      end: TimeOfDay(hour: 22, minute: 0),
    ),
  ];
  String? aiTip;
  bool loadingTip = false;
  FocusPreference selectedFocus = FocusPreference.balanced;
  double knowledgeConfidence = 0.65; // displayed as "65%"

  final TextEditingController topicsController = TextEditingController();

  static const int maxPlans = 3;

  @override
  void dispose() {
    topicsController.dispose();
    super.dispose();
  }

  // ── Methods ────────────────────────────────────────────────────────────────
  // Everything below is UI-only: collecting input, calling AIPlanProvider,
  // showing snackbars, and navigating. All planning/ranking/scheduling logic
  // lives in AIRecommendationService, and all persistence lives in
  // AIPlanService — both reached through AIPlanProvider.

  Future<void> addStudySlot() async {
    final start = await showTimePicker(
      context: context,
      initialTime: const TimeOfDay(hour: 9, minute: 0),
    );
    if (start == null || !mounted) return;

    final end = await showTimePicker(
      context: context,
      initialTime: const TimeOfDay(hour: 10, minute: 0),
    );
    if (end == null) return;

    setState(() => studySlots.add(StudySlot(start: start, end: end)));
  }

  void removeStudySlot(int index) {
    setState(() => studySlots.removeAt(index));
  }

  // Gathers the current form input + existing state, delegates the entire
  // plan-generation flow (ranking tasks, sizing sessions, writing to
  // Firestore, bumping AI usage) to AIPlanProvider, then surfaces the result
  // via a snackbar.
  Future<void> generatePlans() async {
    final tasksAsync = ref.read(taskProvider);
    final user = ref.read(userProvider);

    if (user == null) return;
    setState(() => aiTip = null);
    final tasks = tasksAsync.value ?? [];
    final remainingAiPlans = (maxPlans - (user.aiUsageCount ?? 0)).clamp(
      0,
      maxPlans,
    );

    if (!user.isPremium) {
      final remainingAiPlans = (maxPlans - user.aiUsageCount).clamp(
        0,
        maxPlans,
      );

      if (remainingAiPlans <= 0) {
        AppSnackbar.info(context, 'No AI plans remaining. Upgrade to Pro!');
        return;
      }
    }
    if (tasks.isEmpty) {
      AppSnackbar.info(
        context,
        'Create a task before generating a study plan.',
      );
      return;
    }
    if (studySlots.isEmpty) {
      AppSnackbar.info(
        context,
        'Add at least one study session slot before generating a plan.',
      );
      return;
    }

    final existingPlans = ref.read(aiPlanProvider).value ?? [];

    final usedAI = await ref
        .read(aiPlanNotifierProvider.notifier)
        .generatePlans(
          tasks: tasks,
          studySlots: studySlots,
          preference: selectedFocus,
          confidence: knowledgeConfidence,
          notes: topicsController.text,
          userId: user.uid,
          existingPlans: existingPlans,
          isPremium: user.isPremium,
          increaseAiUsage: () async {
            ref.read(userProvider.notifier).increaseAiUsage();
          },
        );

    if (!mounted) return;
    AppSnackbar.success(
      context,
      usedAI
          ? 'AI study plan generated by Groq.'
          : 'Plan generated (AI unavailable — used backup scheduler).',
    );
    if (usedAI) {
      setState(() => loadingTip = true);
      ref
          .read(groqAIPlanServiceProvider)
          .getStudyTip(tasks: tasks)
          .then((tip) {
            if (!mounted) return;
            setState(() {
              aiTip = tip;
              loadingTip = false;
            });
          })
          .catchError((_) {
            if (mounted) setState(() => loadingTip = false);
            // silently skip — it's a nice-to-have, not core functionality
          });
    }
  }

  // Toggles a single session's completed flag and persists the whole plan
  // back to Firestore via AIPlanProvider. PlannedSession has no sub-step
  // checklist of its own, so this is the closest equivalent of the old
  // per-step toggle.aiPlans.isNotEmpty)
  Future<void> toggleSessionCompletion(AIPlanModel plan, int sessionIdx) async {
    final updatedSessions = [...plan.sessions];
    final session = updatedSessions[sessionIdx];
    updatedSessions[sessionIdx] = session.copyWith(
      completed: !session.completed,
    );

    final updatedPlan = plan.copyWith(sessions: updatedSessions);
    await ref.read(aiPlanNotifierProvider.notifier).updatePlan(updatedPlan);
  }

  void openUpgrade() => Navigator.pushNamed(context, '/upgrade');

  // ── Build ────────── plans
  @override
  Widget build(BuildContext context) {
    final plansAsync = ref.watch(aiPlanProvider);
    final aiPlans = plansAsync.value ?? [];

    final user = ref.watch(userProvider);

    final remainingAiPlans = (maxPlans - (user?.aiUsageCount ?? 0)).clamp(
      0,
      maxPlans,
    );
    return Scaffold(
      backgroundColor: AppColors.background(context),
      body: SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 12),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              // ── Logo ───────────────────────────────────────────────────────
              AppHeader(
                onProfilePressed: () {
                  Navigator.pushNamed(context, ProfileScreen.routeName);
                },
              ),
              const SizedBox(height: 20),

              // ── Page title ─────────────────────────────────────────────────
              const Text(
                'AI Study Planner',
                style: TextStyle(fontSize: 22, fontWeight: FontWeight.bold),
              ),
              const SizedBox(height: 4),
              const Text(
                'Generate an optimized study plans for today',
                style: TextStyle(fontSize: 13, color: Colors.grey),
              ),
              const SizedBox(height: 20),

              // ══════════════════════════════════════════════════════════════
              // SECTION 1: Planner form (top half, image 1)
              // ══════════════════════════════════════════════════════════════
              _buildFormCard(aiPlans),
              const SizedBox(height: 20),

              // ══════════════════════════════════════════════════════════════
              // SECTION 2: Generated plans (bottom half, image 2)
              //   Only shown after the user has generated at least once.
              //   Each AIPlanModel is one task, grouped with its sessions.
              // ══════════════════════════════════════════════════════════════
              if (aiPlans.isNotEmpty) ...[
                const Text(
                  "Today's AI Study Plan",
                  style: TextStyle(fontSize: 20, fontWeight: FontWeight.bold),
                ),
                const SizedBox(height: 12),
                _buildSuccessBanner(),
                if (loadingTip || aiTip != null) ...[
                  const SizedBox(height: 12),
                  loadingTip ? _buildTipLoadingCard() : _buildAiTipCard(aiTip!),
                ],

                const SizedBox(height: 16),
                AITimeline(
                  aiPlans: aiPlans,
                  allowMarkComplete: true,
                  scrollable: false,
                  onToggleComplete: toggleSessionCompletion,
                ),
                if (!(user?.isPremium ?? false)) ...[
                  const SizedBox(height: 16),
                  _buildPlansRemaining(maxPlans, remainingAiPlans),
                  const SizedBox(height: 16),
                  _buildUpgradeBanner(),
                ],
              ],

              const SizedBox(height: 80), // breathing room above bottom nav
            ],
          ),
        ),
      ),
      bottomNavigationBar: const AppBottomNavigation(
        currentIndex: NavigationIndex.planner,
      ),
    );
  }

  // ── Logo ────────────────────────────────────────────────────────────────────

  // ══════════════════════════════════════════════════════════════════════════
  // FORM CARD
  // ══════════════════════════════════════════════════════════════════════════
  Widget _buildFormCard(List<AIPlanModel> aiPlans) {
    final hasPlans = aiPlans.isNotEmpty;
    return WhiteCard(
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          // ── Availability slots ─────────────────────────────────────────
          const SectionLabel('STUDY SESSION AVAILABILITY'),
          const SizedBox(height: 10),
          _buildSlotChips(),

          const SizedBox(height: 20),

          // ── Focus preference ───────────────────────────────────────────
          const SectionLabel('FOCUS PREFERENCE'),
          const SizedBox(height: 10),
          _buildFocusOptions(),

          const SizedBox(height: 20),

          // ── Knowledge confidence slider ────────────────────────────────
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              const SectionLabel('KNOWLEDGE CONFIDENCE'),
              Text(
                '${(knowledgeConfidence * 100).toInt()}%',
                style: const TextStyle(
                  fontSize: 13,
                  fontWeight: FontWeight.bold,
                  color: AppColors.primaryBlue,
                ),
              ),
            ],
          ),
          SliderTheme(
            data: SliderTheme.of(context).copyWith(
              trackHeight: 5,
              thumbShape: const RoundSliderThumbShape(enabledThumbRadius: 8),
              overlayShape: const RoundSliderOverlayShape(overlayRadius: 16),
            ),
            child: Slider(
              value: knowledgeConfidence,
              activeColor: AppColors.primaryBlue,
              inactiveColor: const Color(0xFFE5E9F2),
              onChanged: (v) => setState(() => knowledgeConfidence = v),
            ),
          ),
          Padding(
            padding: const EdgeInsets.symmetric(horizontal: 4),
            child: Row(
              mainAxisAlignment: MainAxisAlignment.spaceBetween,
              children: const [
                Text(
                  'BEGINNER',
                  style: TextStyle(fontSize: 10, color: Colors.grey),
                ),
                Text(
                  'EXPERT',
                  style: TextStyle(fontSize: 10, color: Colors.grey),
                ),
              ],
            ),
          ),
          const SizedBox(height: 20),
          const SectionLabel('ADDITIONAL INSTRUCTIONS (OPTIONAL)'),
          const SizedBox(height: 10),
          TextField(
            controller: topicsController,
            maxLines: 2,
            decoration: InputDecoration(
              hintText:
                  'e.g. "Avoid sessions after 9pm" or "Focus more on Math"',
              hintStyle: const TextStyle(fontSize: 12, color: Colors.grey),
              filled: true,
              fillColor: const Color(0xFFF8F9FC),
              contentPadding: const EdgeInsets.symmetric(
                horizontal: 12,
                vertical: 10,
              ),
              border: OutlineInputBorder(
                borderRadius: BorderRadius.circular(12),
                borderSide: BorderSide.none,
              ),
            ),
            style: const TextStyle(fontSize: 13),
          ),
          const SizedBox(height: 20),

          // ── Generate button ─────────────────────────────────────────
          SizedBox(
            width: double.infinity,
            child: ElevatedButton.icon(
              onPressed: generatePlans,
              icon: const Icon(
                Icons.auto_awesome,
                color: Colors.white,
                size: 18,
              ),
              label: Text(
                hasPlans ? 'Regenerate Plan' : 'Generate Today\'s Plan',
              ),
              style: ElevatedButton.styleFrom(
                backgroundColor: AppColors.primaryBlue,
                foregroundColor: Colors.white,
                padding: const EdgeInsets.symmetric(vertical: 15),
                shape: RoundedRectangleBorder(
                  borderRadius: BorderRadius.circular(12),
                ),
              ),
            ),
          ),
          const SizedBox(height: 8),
          Text(
            hasPlans
                ? 'Regenerating will replace today\'s AI study plan.'
                : 'Generate your personalized AI study plan for today.',
            textAlign: TextAlign.center,
            style: TextStyle(fontSize: 11, color: Colors.grey),
          ),
        ],
      ),
    );
  }

  // Availability slot chips + "+" circle button
  Widget _buildSlotChips() {
    return Wrap(
      spacing: 8,
      runSpacing: 8,
      crossAxisAlignment: WrapCrossAlignment.center,
      children: [
        for (int i = 0; i < studySlots.length; i++)
          Chip(
            label: Text(
              studySlots[i].label,
              style: const TextStyle(
                fontSize: 12,
                color: AppColors.primaryBlue,
              ),
            ),
            backgroundColor: const Color(0xFFE9EEFC),
            deleteIcon: const Icon(
              Icons.close,
              size: 14,
              color: AppColors.primaryBlue,
            ),
            onDeleted: () => removeStudySlot(i),
            shape: RoundedRectangleBorder(
              borderRadius: BorderRadius.circular(20),
              side: BorderSide.none,
            ),
            padding: const EdgeInsets.symmetric(horizontal: 4, vertical: 0),
          ),
        GestureDetector(
          onTap: addStudySlot,
          child: Container(
            width: 32,
            height: 32,
            decoration: BoxDecoration(
              shape: BoxShape.circle,
              border: Border.all(color: Colors.grey.shade400, width: 1.5),
            ),
            child: const Icon(Icons.add, size: 16, color: Colors.grey),
          ),
        ),
      ],
    );
  }

  // Focus preference pill buttons, stacked vertically
  Widget _buildFocusOptions() {
    return Column(
      children: FocusPreference.values.map((focus) {
        final isSelected = selectedFocus == focus;
        return Padding(
          padding: const EdgeInsets.only(bottom: 8),
          child: InkWell(
            onTap: () => setState(() => selectedFocus = focus),
            borderRadius: BorderRadius.circular(24),
            child: Container(
              width: double.infinity,
              padding: const EdgeInsets.symmetric(vertical: 12),
              alignment: Alignment.center,
              decoration: BoxDecoration(
                color: isSelected
                    ? AppColors.primaryBlue
                    : const Color(0xFFF8F9FC),
                borderRadius: BorderRadius.circular(24),
                border: Border.all(
                  color: isSelected
                      ? AppColors.primaryBlue
                      : const Color(0xFFE5E9F2),
                ),
              ),
              child: Text(
                focus.label,
                style: TextStyle(
                  fontSize: 13,
                  fontWeight: FontWeight.w600,
                  color: isSelected ? Colors.white : Colors.black87,
                ),
              ),
            ),
          ),
        );
      }).toList(),
    );
  }

  // ══════════════════════════════════════════════════════════════════════════
  // RESULT SECTION (below the form card)
  // ══════════════════════════════════════════════════════════════════════════

  Widget _buildSuccessBanner() {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: AppColors.card(context),
        borderRadius: BorderRadius.circular(12),
      ),
      child: const Text(
        'Today\'s study sessions have been added to your dashboard timeline.',
        style: TextStyle(fontSize: 12, color: AppColors.green),
      ),
    );
  }

  // "1/3 AI Plans remaining today" progress strip upgrade
  Widget _buildPlansRemaining(int maxPlans, int remainingAiPlans) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Text(
          '$remainingAiPlans/$maxPlans AI Plans Remaining Today',
          style: const TextStyle(
            fontSize: 11,
            fontWeight: FontWeight.w600,
            color: Colors.grey,
          ),
        ),
        const SizedBox(height: 4),
        ClipRRect(
          borderRadius: BorderRadius.circular(4),
          child: LinearProgressIndicator(
            value: remainingAiPlans / maxPlans,
            minHeight: 4,
            backgroundColor: Colors.grey.shade200,
            valueColor: const AlwaysStoppedAnimation<Color>(
              AppColors.primaryBlue,
            ),
          ),
        ),
      ],
    );
  }

  // Dark navy upgrade banner at the very bottom
  Widget _buildUpgradeBanner() {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: AppColors.darkBlue,
        borderRadius: BorderRadius.circular(16),
      ),
      child: Row(
        children: [
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: const [
                Text(
                  'Upgrade to TaskMap Pro',
                  style: TextStyle(
                    color: Colors.white,
                    fontWeight: FontWeight.bold,
                    fontSize: 14,
                  ),
                ),
                SizedBox(height: 4),
                Text(
                  'Unlock unlimited AI planning and deep analytics.',
                  style: TextStyle(color: Colors.white70, fontSize: 11),
                ),
              ],
            ),
          ),
          const SizedBox(width: 10),
          ElevatedButton(
            onPressed: openUpgrade,
            // () => _upgradePlan(context)            ,
            style: ElevatedButton.styleFrom(
              backgroundColor: AppColors.primaryBlue,
              foregroundColor: Colors.white,
              shape: RoundedRectangleBorder(
                borderRadius: BorderRadius.circular(8),
              ),
              padding: const EdgeInsets.symmetric(horizontal: 14, vertical: 10),
            ),
            child: const Text(
              'UPGRADE',
              style: TextStyle(fontSize: 11, fontWeight: FontWeight.bold),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildAiTipCard(String tip) {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: const Color(0xFFFFF8E1),
        borderRadius: BorderRadius.circular(12),
        border: Border.all(color: const Color(0xFFFFE082)),
      ),
      child: Row(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const Text('💡', style: TextStyle(fontSize: 16)),
          const SizedBox(width: 8),
          Expanded(
            child: Text(
              'AI tip: $tip',
              style: const TextStyle(fontSize: 12, height: 1.3),
            ),
          ),
        ],
      ),
    );
  }

  Widget _buildTipLoadingCard() {
    return Container(
      width: double.infinity,
      padding: const EdgeInsets.all(12),
      decoration: BoxDecoration(
        color: const Color(0xFFFFF8E1),
        borderRadius: BorderRadius.circular(12),
        border: Border.all(color: const Color(0xFFFFE082)),
      ),
      child: const Row(
        children: [
          SizedBox(
            width: 12,
            height: 12,
            child: CircularProgressIndicator(strokeWidth: 2),
          ),
          SizedBox(width: 8),
          Text('Getting an AI tip...', style: TextStyle(fontSize: 12)),
        ],
      ),
    );
  }
}
